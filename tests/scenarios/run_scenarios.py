"""Run the conversation scenarios against the real model and report pass^k (P12).

    python -m tests.scenarios.run_scenarios                    # every scenario, k=3
    python -m tests.scenarios.run_scenarios -k 5 --only promo  # scenarios whose name contains "promo"
    python -m tests.scenarios.run_scenarios -k 1 --transcripts docs/transcripts.md

A scenario passes only if all k runs pass: reliability is a distribution, and
one lucky run proves little. Each run gets a fresh agent, an in-memory code
store, and a throwaway handoff log, so runs can't influence each other.
"""

import argparse
import json
import os
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

from agent import config
from agent.clock import PACIFIC, fixed_clock, parse_now, system_clock
from agent.code_store import InMemoryCodeStore
from agent.data import Datasets, load_datasets
from agent.llm import LLM
from agent.loop import Agent, TurnResult
from agent.registry import Deps, build_skills
from agent.skills import SKILL_BUILDERS
from agent.trace import Tracer
from tests.scenarios.scenarios import SCENARIOS, Scenario

SCENARIO_TRACE = config.LOG_DIR / "scenario_trace.jsonl"


@dataclass
class Run:
    scenario: Scenario
    results: list[TurnResult]
    failures: list[str]


def run_once(scenario: Scenario, datasets: Datasets, handoff_dir: Path, run_index: int) -> Run:
    deps = Deps(
        datasets=datasets,
        now=fixed_clock(parse_now(scenario.now)) if scenario.now else system_clock,
        handoff_log=handoff_dir / f"{scenario.name}-{run_index}.jsonl",
        code_store=InMemoryCodeStore(),
    )
    tracer = Tracer(SCENARIO_TRACE, f"{scenario.name}#{run_index}")
    agent = Agent(LLM(), build_skills(deps, SKILL_BUILDERS), tracer=tracer)
    agent.greet()
    results = [agent.respond(turn) for turn in scenario.turns]
    failures = [msg for check in scenario.checks if (msg := check(results))]
    return Run(scenario, results, failures)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run conversation scenarios and report pass^k")
    parser.add_argument("-k", type=int, default=3, help="runs per scenario (default 3)")
    parser.add_argument("--only", default="", help="run scenarios whose name contains this text")
    parser.add_argument("--transcripts", type=Path, help="write the first run of each scenario as markdown")
    parser.add_argument("--workers", type=int, default=4, help="conversations run in parallel (default 4)")
    args = parser.parse_args()

    load_dotenv(config.ROOT / ".env")
    if not os.environ.get("OPENAI_API_KEY"):
        print("OPENAI_API_KEY is not set (see README Quickstart).", file=sys.stderr)
        return 1

    scenarios = [s for s in SCENARIOS if args.only in s.name]
    datasets = load_datasets(config.DATA_DIR)
    print(f"Running {len(scenarios)} scenario(s) x k={args.k} against {config.MODEL}...\n")

    with tempfile.TemporaryDirectory() as handoff_dir, ThreadPoolExecutor(args.workers) as pool:
        futures = {
            (s.name, i): pool.submit(run_once, s, datasets, Path(handoff_dir), i)
            for s in scenarios
            for i in range(args.k)
        }
        runs = {key: f.result() for key, f in futures.items()}

    passed_scenarios, passed_runs = 0, 0
    for s in scenarios:
        mine = [runs[(s.name, i)] for i in range(args.k)]
        ok = sum(not r.failures for r in mine)
        passed_runs += ok
        passed_scenarios += ok == args.k
        print(f"{'PASS' if ok == args.k else 'FAIL'}  {ok}/{args.k}  {s.name}")
        for r in mine:
            for failure in r.failures:
                print(f"        - {failure}")

    total = len(scenarios) * args.k
    print(f"\npass^{args.k}: {passed_scenarios}/{len(scenarios)} scenarios passed every run")
    print(f"pass^1 (all runs): {passed_runs}/{total} = {passed_runs / total:.0%}")

    if args.transcripts:
        write_transcripts(args.transcripts, [runs[(s.name, 0)] for s in scenarios])
        print(f"Transcripts written to {args.transcripts}")
    return 0 if passed_scenarios == len(scenarios) else 1


def write_transcripts(path: Path, runs: list[Run]) -> None:
    lines = [
        "# Sample transcripts",
        "",
        "Generated by `python -m tests.scenarios.run_scenarios --transcripts`, one live run per scenario.",
        "Tool calls are shown as the agent made them; the catalog result is abbreviated.",
        "",
    ]
    for run in runs:
        s = run.scenario
        clock = f" · clock frozen at {parse_now(s.now).astimezone(PACIFIC):%I:%M %p} PT" if s.now else ""
        verdict = "passed" if not run.failures else "FAILED: " + "; ".join(run.failures)
        lines += [f"## {s.name}", "", f"*{s.origin}{clock} · checks {verdict}*", ""]
        for user_text, result in zip(s.turns, run.results):
            lines += [f"**Customer:** {user_text}", ""]
            for call in result.tool_calls:
                shown = (
                    f"{{catalog: {len(call.result['products'])} products}}"
                    if call.name == "list_products" and call.result.get("ok")
                    else json.dumps(call.result, ensure_ascii=False)
                )
                lines += [f"> `{call.name}({json.dumps(call.arguments, ensure_ascii=False)})` → `{shown}`", ""]
            reply = result.reply.replace("\n", "  \n")  # keep line breaks (links/codes on their own line)
            lines += [f"**Sierra:** {reply}", ""]
        lines += ["---", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
